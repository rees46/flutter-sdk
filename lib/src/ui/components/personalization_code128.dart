/// Кодировщик штрихкода Code 128 — то, что рисует `PersonalizationBarcode`.
///
/// Номер карты лояльности в макете (Wallet/Code, 520:8886) — линейный штрихкод,
/// а Code 128 — формат, который читают кассовые сканеры и Apple Wallet.
/// Библиотеку ради сотни строк таблицы SDK не тянет.
///
/// Набор выбирается целиком на строку: одни цифры — набор C (две цифры на символ,
/// код вдвое короче), при нечётной длине последняя цифра уходит в набор B через
/// переключатель CODE B. Всё прочее — набор B, печатный ASCII 32…126. Строку с
/// другими символами Code 128 без расширений не несёт — тогда кодировщик
/// возвращает null, и штрихкода нет.
///
/// В барель кита не входит: это внутренность штрихкода, наружу торчит только
/// виджет. Тесты импортируют файл напрямую.
abstract final class PersonalizationCode128 {
  /// Символы строки: значения по порядку, от старт-символа до контрольного
  /// включительно. Строку, которую набор не несёт, — null.
  static List<int>? values(String text) {
    if (text.isEmpty) return null;
    final units = text.codeUnits;
    if (units.any((unit) => unit < 32 || unit > 126)) return null;

    final values = <int>[];
    final digits = units.every((unit) => unit >= 0x30 && unit <= 0x39);
    if (digits && units.length >= 2) {
      values.add(_startC);
      final pairs = units.length ~/ 2;
      for (int i = 0; i < pairs; i++) {
        values.add(int.parse(text.substring(i * 2, i * 2 + 2)));
      }
      if (units.length.isOdd) {
        values
          ..add(_codeB)
          ..add(units.last - 32);
      }
    } else {
      values.add(_startB);
      for (final unit in units) {
        values.add(unit - 32);
      }
    }
    values.add(checksum(values));
    return values;
  }

  /// Модули слева направо, `true` — штрих. Тихих зон по краям нет — их даёт
  /// подложка.
  static List<bool>? encode(String text) {
    final symbols = values(text);
    if (symbols == null) return null;
    final modules = <bool>[];
    for (final value in <int>[...symbols, _stop]) {
      final pattern = _patterns[value];
      for (int i = 0; i < pattern.length; i++) {
        final width = pattern.codeUnitAt(i) - 0x30;
        // Ширины идут парами «штрих, пробел», начиная со штриха.
        for (int k = 0; k < width; k++) {
          modules.add(i.isEven);
        }
      }
    }
    return modules;
  }

  /// Старт-символ плюс сумма значений, взвешенных позицией с единицы, по
  /// модулю 103. [symbols] — от старт-символа до последнего символа данных.
  static int checksum(List<int> symbols) {
    int sum = symbols.first;
    for (int i = 1; i < symbols.length; i++) {
      sum += i * symbols[i];
    }
    return sum % 103;
  }

  static const int _codeB = 100;
  static const int _startB = 104;
  static const int _startC = 105;
  static const int _stop = 106;

  /// Ширины штрихов и пробелов символа, начиная со штриха; индекс — значение
  /// символа. 103–105 — старт-символы A/B/C, 106 — стоп (13 модулей).
  static const List<String> _patterns = <String>[
    '212222', '222122', '222221', '121223', '121322', '131222', '122213', //
    '122312', '132212', '221213', '221312', '231212', '112232', '122132', //
    '122231', '113222', '123122', '123221', '223211', '221132', '221231', //
    '213212', '223112', '312131', '311222', '321122', '321221', '312212', //
    '322112', '322211', '212123', '212321', '232121', '111323', '131123', //
    '131321', '112313', '132113', '132311', '211313', '231113', '231311', //
    '112133', '112331', '132131', '113123', '113321', '133121', '313121', //
    '211331', '231131', '213113', '213311', '213131', '311123', '311321', //
    '331121', '312113', '312311', '332111', '314111', '221411', '431111', //
    '111224', '111422', '121124', '121421', '141122', '141221', '112214', //
    '112412', '122114', '122411', '142112', '142211', '241211', '221114', //
    '413111', '241112', '134111', '111242', '121142', '121241', '114212', //
    '124112', '124211', '411212', '421112', '421211', '212141', '214121', //
